export function adhkarForDate(d: Date = new Date()): string {
  const start = new Date(d.getFullYear(), 0, 0);
  const day = Math.floor((d.getTime() - start.getTime()) / 86400000);
  return ADHKAR[day % ADHKAR.length];
}

